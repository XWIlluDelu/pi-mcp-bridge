// Another admitted operation holds the owner; nothing was dispatched.
const BUSY_REFUSALS = ['STOP_IN_PROGRESS', 'BASH_IN_PROGRESS', 'RELOAD_IN_PROGRESS'];
const OWNED_COMPACT_REFUSALS = [
  'COMPACT_BUSY',
  'PI_REJECTED',
  'INVALID_ARGUMENTS',
  'RUNTIME_SHUTTING_DOWN',
];

export const isOwnerMutation = (op) =>
  typeof op === 'string' && Object.hasOwn(DEFINITE_REFUSALS, op);

export function isDefiniteOwnerRefusal(op, code, ownedCompact) {
  if (ownedCompact) return OWNED_COMPACT_REFUSALS.includes(code);
  return (
    (isOwnerMutation(op) && DEFINITE_REFUSALS[op].includes(code)) ||
    (op !== 'seal' && BUSY_REFUSALS.includes(code))
  );
}

